import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'

const claimFixture = (name: string) => resolve('../../data/synthetic/claim-routing', `${name}.pdf`)

test('explains evidence by insurance type and invalidates a pending lookup on selection change', async ({ page }) => {
  await page.goto('/')
  let posts = 0
  page.on('request', request => { if (request.method() === 'POST') posts++ })
  const picker = page.getByRole('region', { name: '어떤 보험으로 검토할까요?' })
  await expect(picker).toHaveCount(0)
  const samplePair = ['public/samples/details.pdf', 'public/samples/receipt.pdf'].map(name => resolve(name))
  await page.getByLabel('영수증과 세부내역서 선택').setInputFiles(samplePair)
  await expect(picker.getByRole('heading')).toBeFocused()
  const files = page.getByRole('list', { name: '선택한 PDF' })
  await expect(files.getByRole('listitem').first()).toContainText('진료비 세부내역서')
  await expect(files.getByRole('listitem').last()).toContainText('진료비 영수증')
  await expect(picker.getByRole('radio', { name: '실손보험' })).toBeChecked()
  await expect(picker).toContainText('비급여 MRI 미확인')
  await page.getByLabel('비급여 MRI 가입 상태').selectOption('not_enrolled')
  await expect(picker).toContainText('비급여 MRI 미가입')
  await expect(picker).toContainText('진단서 필요')
  await expect(picker).toContainText('사망 증빙 필요')

  const attach = page.getByLabel('추가 PDF 선택')
  await attach.setInputFiles(resolve('public/samples/supplements/diagnosis.pdf'))
  await expect(picker).toContainText('분류 확인 필요')
  await expect(picker).not.toContainText('라이나 약관의 분류 후보')
  await attach.setInputFiles([claimFixture('c44-diagnosis'), claimFixture('c50-diagnosis')])
  await expect(picker).toContainText('C44.9 → 기타피부암 치료보험금')
  await expect(picker).toContainText('C50.9 → 암치료보험금')

  await page.getByLabel('항목과 합계 검토 완료').check()
  await page.getByRole('button', { name: '전송 내용 확인', exact: true }).click()
  await expect(page.getByLabel('전송 내용 확인', { exact: true })).toBeVisible()
  await picker.getByRole('radio', { name: '암보험' }).check()
  await expect(picker.getByRole('status')).toContainText('암보험을 선택했습니다')
  await expect(page.getByLabel('전송 내용 확인', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'c44-diagnosis.pdf 빼기' }).click()
  await expect(picker).not.toContainText('C44.9')
  await expect(picker).toContainText('C50.9')
  await picker.getByRole('radio', { name: '종신보험' }).check()
  await expect(picker.getByRole('status')).toContainText('종신보험을 선택했습니다')
  await picker.getByRole('radio', { name: '실손보험' }).check()
  await expect(page.getByRole('button', { name: '전송 내용 확인', exact: true })).toBeDisabled()
  await expect(page.getByLabel('구조화한 추가 서류')).toContainText('c50-diagnosis.pdf')
  expect(posts).toBe(0)
  await picker.screenshot({ path: test.info().outputPath('claim-routing-desktop.png') })
})

test('groups both policy types and displays readable claim options on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '약관 라이브러리', exact: true }).click()
  const indemnity = page.getByRole('region', { name: '실손보험 약관', exact: true })
  const fixed = page.getByRole('region', { name: '정액보험 약관', exact: true })
  await expect(indemnity.getByRole('article')).toHaveCount(2)
  await expect(fixed.getByRole('article')).toHaveCount(2)
  await expect(indemnity.getByRole('link', { name: '공식 약관 PDF' })).toHaveAttribute('href', /samsungfire\.com\/docs\/realloss\.pdf$/)
  await page.locator('main').screenshot({ path: test.info().outputPath('policy-cards-mobile.png') })
  await page.getByPlaceholder('상품명 또는 보험사 검색').fill('2605.1')
  await expect(indemnity.getByRole('article')).toHaveCount(1)
  await expect(fixed.getByRole('article')).toHaveCount(0)
  await page.getByRole('button', { name: '개인정보 보호 분석', exact: true }).click()
  await page.getByRole('button', { name: '가상 샘플로 시작', exact: true }).click()
  const picker = page.getByRole('region', { name: '어떤 보험으로 검토할까요?' })
  await expect(picker.getByRole('radio')).toHaveCount(3)
  expect(await picker.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await picker.screenshot({ path: test.info().outputPath('claim-routing-mobile.png') })
  await page.getByLabel('기본 서류 샘플').screenshot({ path: test.info().outputPath('document-cards-mobile.png') })
})
